"""notes.py — speaker-notes handout with the source of every number on every slide.

    .venv/bin/python export/notes.py        → export/out/notes.md

For each slide (in deck order, with its displayed number): the title, the speaker notes, and every
bound number: its value, the trace file and JSON path it comes from, and the tests that read that
trace. Paper numbers carry their table (traces/paper.py); typed structural numbers are not listed.
"""
from __future__ import annotations

import json
import re
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
sys_path = str(ROOT)


def get(obj, path):
    for k in path.split("."):
        if obj is None:
            return None
        if isinstance(obj, list):
            obj = obj[int(k)] if k.isdigit() and int(k) < len(obj) else (len(obj) if k == "length" else None)
        else:
            obj = obj.get(k)
    return obj


class Deck(HTMLParser):
    """Collect leaf sections: id, title text, notes text, data-bind keys, figure traces."""

    def __init__(self):
        super().__init__()
        self.slides, self.stack, self.cur = [], [], None
        self.in_h, self.in_notes, self.depth = False, False, 0

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "section":
            self.depth += 1
            sec = {"id": a.get("id", ""), "title": "", "notes": "", "binds": [], "figs": [], "depth": self.depth,
                   "clip": "clip-slide" in (a.get("class") or ""), "clip_title": a.get("data-title", "")}
            self.stack.append(sec)
            self.cur = sec
            return
        if self.cur is None:
            return
        if tag in ("h1", "h2"):
            self.in_h = True
        if tag == "aside" and "notes" in (a.get("class") or ""):
            self.in_notes = True
        if "data-bind" in a:
            self.cur["binds"].append(a["data-bind"])
        if "data-fig" in a and a.get("data-trace"):
            self.cur["figs"].append((a["data-fig"], a["data-trace"]))
        if tag == "span" and "data-bind" in a and self.in_h:
            self.cur["title"] += "{" + a["data-bind"] + "}"

    def handle_endtag(self, tag):
        if tag == "section":
            sec = self.stack.pop()
            self.depth -= 1
            if sec["id"]:                       # stack wrappers have no id
                self.slides.append(sec)
            self.cur = self.stack[-1] if self.stack else None
        if tag in ("h1", "h2"):
            self.in_h = False
        if tag == "aside":
            self.in_notes = False

    def handle_data(self, data):
        if self.cur is None:
            return
        if self.in_h:
            self.cur["title"] += data
        elif self.in_notes:
            self.cur["notes"] += data


def tests_by_trace():
    out = {}
    for f in (ROOT / "traces" / "tests").glob("test_*.py"):
        text = f.read_text()
        for m in re.finditer(r"def (test_\w+)\(.*?\):(.*?)(?=\ndef |\Z)", text, re.S):
            name, body = m.group(1), m.group(2)
            for fid in set(re.findall(r'load\("([A-Za-z0-9_]+)"\)', body)):
                out.setdefault(fid, []).append(f"{f.name}::{name}")
    return out


def main():
    html = (ROOT / "deck" / "index.html").read_text()
    deck = Deck()
    deck.feed(html)
    # deck.slides is in end-tag order; restore document order by position of the id
    pos = {s["id"]: html.find(f'id="{s["id"]}"') for s in deck.slides}
    slides = sorted(deck.slides, key=lambda s: pos[s["id"]])
    tests = tests_by_trace()
    cache = {}

    def value(bind):
        fid, path = bind.split(":", 1)
        if fid not in cache:
            p = DATA / f"{fid}.json"
            cache[fid] = json.loads(p.read_text()) if p.exists() else None
        v = get(cache[fid], path) if cache[fid] is not None else None
        return v, fid, path

    lines = ["# Speaker notes and number sources", "",
             "Generated by `export/notes.py` from `deck/index.html` and `data/*.json`. "
             "Each bound number: value — trace file : JSON path — tests that assert that trace. "
             "Paper numbers come from `traces/paper.py` (tables cited in each slide's notes; see `notes/paper-facts.md`).", ""]
    h, missing = 0, 0
    for s in slides:
        if s["clip"]:
            num = f"{h}.2"
        else:
            h += 1
            num = str(h)
        title = re.sub(r"\{([^}]+)\}", lambda m: str(value(m.group(1))[0]), s["title"]).strip() or s["clip_title"]
        title = re.sub(r"\s+", " ", title)
        lines += [f"## {num}. {title}", f"*section `{s['id']}`*", ""]
        notes = re.sub(r"\s+", " ", s["notes"]).strip()
        if notes:
            lines += [notes, ""]
        figs = sorted({t for _, t in s["figs"]})
        if figs:
            lines += ["Figures drawn from: " + ", ".join(f"`data/{t}.json`" for t in figs), ""]
        seen = []
        for b in s["binds"]:
            if b in seen:
                continue
            seen.append(b)
        if seen:
            lines += ["| value | source | asserted by |", "|---|---|---|"]
            for b in seen:
                v, fid, path = value(b)
                if v is None:
                    missing += 1
                if isinstance(v, list):
                    v = ", ".join(map(str, v))
                t = tests.get(fid, [])
                lines.append(f"| {v} | `data/{fid}.json` : `{path}` | {', '.join(f'`{x}`' for x in t) or '—'} |")
            lines.append("")
    out = ROOT / "export" / "out" / "notes.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    n_binds = sum(len(set(s["binds"])) for s in slides)
    print(f"{out.relative_to(ROOT)}: {len(slides)} slides, {n_binds} bound numbers, {missing} unresolved")


if __name__ == "__main__":
    main()
