"""run_solvers.py — measure the anytime curve for slide 42 (proposal slide 40) and write data/S42.json.

    .venv/bin/python -m traces.run_solvers

Not part of figures.BUILDERS (minutes of wall-clock time, timing-dependent results); its output is
validated by tests (every decomposition checked against the three axioms) but not regenerated by them.
"""
from __future__ import annotations

import json
import math
import sys
import time

import networkx as nx

from .circuits import brickwork_circuit, circuit_tn
from .carving import order_to_tree, tree_stats
from .circuits import default_circuit
from .core import index_graph
from .td import td_to_order
from .fast_elim import best_width_first_seed
from .figures import DATA, write_doc
from .solvers import run

INSTANCE = {"rows": 5, "cols": 5, "cycles": 16, "seed": 0}
BUDGETS = [1, 10, 60]
SEEDS = [1, 2, 3]


def mmd_lower_bound(G: nx.Graph) -> int:
    """Minor-min-width lower bound on treewidth: repeatedly contract a min-degree vertex into its
    min-degree neighbour, recording the largest minimum degree seen."""
    H = nx.Graph(G)
    lb = 0
    while H.number_of_nodes() > 1:
        v = min(H, key=lambda u: (H.degree(u), str(u)))
        lb = max(lb, H.degree(v))
        if H.degree(v) == 0:
            H.remove_node(v)
            continue
        u = min(H[v], key=lambda w: (H.degree(w), str(w)))
        H = nx.contracted_nodes(H, u, v, self_loops=False)
    return lb


def main():
    G = index_graph(circuit_tn(brickwork_circuit(**INSTANCE)))
    runs = []
    t0 = time.time()
    for solver in ("tamaki", "jdrasil"):
        for b in BUDGETS:
            for s in SEEDS:
                r = run(solver, G, b, seed=s)
                runs.append({k: r[k] for k in ("solver", "budget", "seed", "width", "valid", "elapsed")})
                print(r["solver"], b, s, r["width"], r["valid"], f"{time.time() - t0:.0f}s", flush=True)
    _, mf, _ = best_width_first_seed(G, "minfill", range(10))
    write_doc("S42", "chart", {"title": "Anytime treewidth heuristics", "instance": INSTANCE},
              {"n": G.number_of_nodes(), "m": G.number_of_edges(), "runs": runs, "minfill": mf,
               "lower_bound": mmd_lower_bound(G), "budgets": BUDGETS, "seeds": SEEDS})
    rechart()
    print("wrote data/S42.json")


def rechart():
    """Best width per solver and budget (over seeds) and the chart, from the stored runs (no re-running)."""
    path = DATA / "S42.json"
    d = json.loads(path.read_text())
    best = {sv: {str(b): min(r["width"] for r in d["runs"] if r["solver"] == sv and r["budget"] == b) for b in d["budgets"]}
            for sv in ("tamaki", "jdrasil")}
    xs = [round(math.log10(b), 3) for b in d["budgets"]]
    d["best"] = best
    d["chart"] = {"xlabel": "time budget per run (s, log scale)", "ylabel": "best width over 3 seeds",
                  "xticks": xs, "xticklabels": [str(b) for b in d["budgets"]], "xmin": -0.1, "xmax": xs[-1] + 0.1,
                  "ymin": 20, "ymax": 40,
                  "series": [{"name": "Tamaki", "x": xs, "y": [best["tamaki"][str(b)] for b in d["budgets"]], "cls": "accent"},
                             {"name": "Jdrasil", "x": xs, "y": [best["jdrasil"][str(b)] for b in d["budgets"]], "cls": "side-b"},
                             {"name": "MinFill (instant)", "x": [xs[0], xs[-1]], "y": [d["minfill"]] * 2, "cls": "muted", "dashed": True}]}
    path.write_text(json.dumps(d, indent=1))


def small():
    """Scorecard runs on the talk's circuit (index graph, 54 indices): 10 s per run, 3 seeds; the best
    decomposition is turned into an elimination order and a pairwise contraction tree."""
    T = circuit_tn(default_circuit())
    G = index_graph(T)
    out = {}
    for solver in ("tamaki", "jdrasil"):
        rs = [run(solver, G, 10, seed=s) for s in SEEDS]
        best = min((r for r in rs if r["valid"]), key=lambda r: r["width"])
        order = td_to_order(G, best["bag_list"])
        st = tree_stats(T, order_to_tree(T, order))
        out[solver] = {"widths": [r["width"] for r in rs], "valid": all(r["valid"] for r in rs), "best_width": best["width"],
                       "tree_max_rank": st["max_rank"], "tree_log2cost": round(st["log2cost"], 2), "order": order}
        print(solver, out[solver], flush=True)
    write_doc("S44", "table", {"title": "Solvers on the talk's circuit", "budget_s": 10, "seeds": SEEDS}, {"rows": out})
    print("wrote data/S44.json")


if __name__ == "__main__":
    {"rechart": rechart, "small": small}.get(sys.argv[1] if len(sys.argv) > 1 else "", main)()
